CREATE TABLE IF NOT EXISTS WATER_LOG (
    id INT AUTO_INCREMENT PRIMARY KEY,
    userId VARCHAR(64) NOT NULL REFERENCES USERS(user_id),
    amount FLOAT NOT NULL,
    loggedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
